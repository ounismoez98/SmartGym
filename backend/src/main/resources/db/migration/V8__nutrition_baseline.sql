CREATE TABLE IF NOT EXISTS public.nutrition_body_measurements (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    arm_cm double precision NOT NULL,
    chest_cm double precision NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    hip_cm double precision NOT NULL,
    measurement_date date NOT NULL,
    notes character varying(300),
    subject character varying(64) NOT NULL,
    thigh_cm double precision NOT NULL,
    waist_cm double precision NOT NULL,
    weight_kg double precision NOT NULL,
    CONSTRAINT nutrition_body_measurements_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS public.nutrition_foods (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    brand character varying(150),
    calories double precision NOT NULL,
    carbohydrate_grams double precision NOT NULL,
    fat_grams double precision NOT NULL,
    fiber_grams double precision NOT NULL,
    name character varying(150) NOT NULL,
    protein_grams double precision NOT NULL,
    serving_size_grams integer NOT NULL,
    sodium_mg double precision NOT NULL,
    subject character varying(150) NOT NULL,
    CONSTRAINT nutrition_foods_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS public.nutrition_meal_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    description character varying(500),
    meal_type character varying(40) NOT NULL,
    name character varying(120) NOT NULL,
    subject character varying(64) NOT NULL,
    target_calories double precision NOT NULL,
    CONSTRAINT nutrition_meal_plans_pkey PRIMARY KEY (id),
    CONSTRAINT nutrition_meal_plans_meal_type_check
        CHECK (meal_type IN ('BREAKFAST', 'LUNCH', 'DINNER', 'SNACK', 'PRE_WORKOUT', 'POST_WORKOUT'))
);

CREATE TABLE IF NOT EXISTS public.nutrition_meal_plan_items (
    meal_plan_id bigint NOT NULL,
    food_id bigint NOT NULL,
    food_name character varying(150),
    servings double precision NOT NULL,
    CONSTRAINT fkrtuhpy1umlsqhmlto8oh64qxl
        FOREIGN KEY (meal_plan_id) REFERENCES public.nutrition_meal_plans (id)
);

CREATE TABLE IF NOT EXISTS public.nutrition_food_journal (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    entry_date date NOT NULL,
    food_id bigint NOT NULL,
    meal_type character varying(40) NOT NULL,
    notes character varying(300),
    servings double precision NOT NULL,
    subject character varying(64) NOT NULL,
    CONSTRAINT nutrition_food_journal_pkey PRIMARY KEY (id),
    CONSTRAINT nutrition_food_journal_meal_type_check
        CHECK (meal_type IN ('BREAKFAST', 'LUNCH', 'DINNER', 'SNACK', 'PRE_WORKOUT', 'POST_WORKOUT'))
);

CREATE TABLE IF NOT EXISTS public.nutrition_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    activity_level character varying(80) NOT NULL,
    age integer,
    created_at timestamp(6) with time zone NOT NULL,
    dietary_preference character varying(80) NOT NULL,
    goal character varying(50) NOT NULL,
    height_cm double precision,
    profile_name character varying(120) NOT NULL,
    subject character varying(64) NOT NULL,
    target_calories integer,
    weight_kg double precision,
    CONSTRAINT nutrition_profiles_pkey PRIMARY KEY (id)
);
