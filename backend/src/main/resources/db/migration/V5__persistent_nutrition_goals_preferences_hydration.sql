ALTER TABLE public.nutrition_profiles
    ADD CONSTRAINT nutrition_profiles_target_weight_check
        CHECK (target_weight_kg IS NULL OR target_weight_kg > 0),
    ADD CONSTRAINT nutrition_profiles_preparation_minutes_check
        CHECK (max_preparation_minutes IS NULL OR max_preparation_minutes BETWEEN 5 AND 240);

CREATE TABLE public.nutrition_hydration_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    subject character varying(64) NOT NULL,
    consumed_at timestamp(6) with time zone NOT NULL,
    water_ml integer NOT NULL,
    CONSTRAINT nutrition_hydration_logs_pkey PRIMARY KEY (id),
    CONSTRAINT nutrition_hydration_logs_water_check CHECK (water_ml BETWEEN 1 AND 2000)
);

CREATE INDEX nutrition_hydration_logs_subject_consumed_at_idx
    ON public.nutrition_hydration_logs (subject, consumed_at DESC);
