CREATE TABLE public.nutrition_profile_allergies (
    nutrition_profile_id bigint NOT NULL,
    allergy character varying(100) NOT NULL,
    CONSTRAINT nutrition_profile_allergies_pkey PRIMARY KEY (nutrition_profile_id, allergy),
    CONSTRAINT fk_nutrition_profile_allergies_profile
        FOREIGN KEY (nutrition_profile_id) REFERENCES public.nutrition_profiles (id) ON DELETE CASCADE
);

