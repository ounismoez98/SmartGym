CREATE TABLE public.nutrition_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    subject character varying(64) NOT NULL,
    name character varying(120) NOT NULL,
    goal character varying(100) NOT NULL,
    plan_type character varying(16) NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    generation_context_id uuid NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT nutrition_plans_pkey PRIMARY KEY (id),
    CONSTRAINT nutrition_plans_type_check CHECK (plan_type IN ('DAILY', 'WEEKLY')),
    CONSTRAINT nutrition_plans_date_range_check CHECK (
        (plan_type = 'DAILY' AND end_date = start_date)
        OR (plan_type = 'WEEKLY' AND end_date = start_date + 6)
    ),
    CONSTRAINT fk_nutrition_plans_generation_context
        FOREIGN KEY (generation_context_id)
        REFERENCES public.nutrition_meal_plan_generation_contexts (id)
);

CREATE INDEX nutrition_plans_subject_start_date_idx
    ON public.nutrition_plans (subject, start_date DESC);

CREATE TABLE public.nutrition_plan_days (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nutrition_plan_id bigint NOT NULL,
    plan_date date NOT NULL,
    CONSTRAINT nutrition_plan_days_pkey PRIMARY KEY (id),
    CONSTRAINT nutrition_plan_days_plan_date_key UNIQUE (nutrition_plan_id, plan_date),
    CONSTRAINT fk_nutrition_plan_days_plan
        FOREIGN KEY (nutrition_plan_id)
        REFERENCES public.nutrition_plans (id)
        ON DELETE CASCADE
);

CREATE TABLE public.nutrition_plan_meals (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nutrition_plan_day_id bigint NOT NULL,
    meal_position integer NOT NULL,
    name character varying(120) NOT NULL,
    meal_type character varying(40) NOT NULL,
    serving_size_grams integer NOT NULL,
    preparation_instructions character varying(2000) NOT NULL,
    calories double precision NOT NULL,
    protein_grams double precision NOT NULL,
    carbohydrate_grams double precision NOT NULL,
    fat_grams double precision NOT NULL,
    fiber_grams double precision NOT NULL,
    sodium_mg double precision NOT NULL,
    nutrition_source character varying(32) NOT NULL,
    CONSTRAINT nutrition_plan_meals_pkey PRIMARY KEY (id),
    CONSTRAINT nutrition_plan_meals_type_check
        CHECK (meal_type IN ('BREAKFAST', 'LUNCH', 'DINNER', 'SNACK', 'PRE_WORKOUT', 'POST_WORKOUT')),
    CONSTRAINT nutrition_plan_meals_serving_check CHECK (serving_size_grams > 0),
    CONSTRAINT fk_nutrition_plan_meals_day
        FOREIGN KEY (nutrition_plan_day_id)
        REFERENCES public.nutrition_plan_days (id)
        ON DELETE CASCADE
);

CREATE TABLE public.nutrition_plan_meal_items (
    nutrition_plan_meal_id bigint NOT NULL,
    item_position integer NOT NULL,
    food_id bigint,
    food_name character varying(150) NOT NULL,
    servings double precision NOT NULL,
    CONSTRAINT nutrition_plan_meal_items_pkey PRIMARY KEY (nutrition_plan_meal_id, item_position),
    CONSTRAINT nutrition_plan_meal_items_servings_check CHECK (servings > 0),
    CONSTRAINT fk_nutrition_plan_meal_items_meal
        FOREIGN KEY (nutrition_plan_meal_id)
        REFERENCES public.nutrition_plan_meals (id)
        ON DELETE CASCADE
);
